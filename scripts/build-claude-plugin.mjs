import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MINIMUM_NODE = '22.0.0';
const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const result = await build({
  absWorkingDir: root, entryPoints: ['scripts/mcp-stdio.mjs'],
  outfile: 'claude-code/server.mjs', bundle: true, write: false,
  format: 'esm', platform: 'node', target: 'node22', minify: true,
  // The bundle is plain JavaScript, so it does not need the source entry's type stripping.
  define: { PACKAGE_SCOUT_MINIMUM_NODE: JSON.stringify(MINIMUM_NODE) },
  banner: { js: '// Generated by npm run plugin:build. Edit scripts/mcp-stdio.mjs and the shared Worker source.' },
});
const files = new Map([
  ['claude-code/server.mjs', result.outputFiles[0].contents],
  ['claude-code/skills/scout/references/package-discovery.md', await readFile(resolve(root, 'plugin/skills/package-discovery/SKILL.md'))],
]);
for (const [name, contents] of files) {
  const path = resolve(root, name);
  if (check) {
    const current = await readFile(path).catch(() => null);
    if (!current || !current.equals(Buffer.from(contents))) throw new Error(`${name} is stale. Run npm run plugin:build.`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, contents);
  }
}
console.log(check ? 'Claude Code bundle matches its source' : 'Built the self-contained Claude Code plugin');
